rulebook = """

🎴 Card Values

• 2 through 10: Face value.
• Jack, Queen, King: Worth 10 points.
• Ace: Worth 1 or 11 points (whichever benefits you more).

🕹️ Gameplay Flow

1. Place Bet: You place your chips on the table.
2. The Deal: You get two face-up cards. The dealer gets one face-up and one face-down card.
3. Your Turn: Choose an action until you stand or exceed 21 (bust).
4. Dealer's Turn: The dealer reveals their hidden card and must hit until they reach at least 17.

🎬 Core Player Actions

• Hit: Take another card.
• Stand: Keep your current total and end your turn.
• Double Down: Double your bet for exactly one more card.
• Split: Separate a pair into two hands by matching your original bet.

🏆 Outcomes

• Win (Pays 1:1): Your total is closer to 21 than the dealer's, or the dealer busts.
• Blackjack (Pays 3:2): An Ace and a 10-value card on your first two cards.
• Lose: You bust, or the dealer's total is closer to 21.
• Push: A tie; your bet is returned.

"""